/**
 * Turn a video into the scroll-scrubbed frame sequence on the home page.
 *
 *   pnpm exec tsx scripts/make-sequence.ts <video.mp4> [--mobile <vertical.mp4>] [--frames 96] [--start 0] [--end <sec>]
 *
 * --mobile: a vertical (9:16) cut of the same shot for phones, so a wide car isn't cropped to
 * its middle third on a tall screen. Without it, phones get the main clip scaled down.
 *
 * Writes evenly spaced WebP frames for desktop (1600px wide) and phones (900px wide) to
 * public/media/transform/{d,m}/001.webp…, plus a poster of the last frame, and regenerates
 * lib/media/sequences.ts so the page knows the frame count and aspect ratio.
 * Needs ffmpeg/ffprobe on PATH (with libwebp).
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const args = process.argv.slice(2);
const valueFlags = new Set(["--mobile", "--frames", "--start", "--end"]);
const video = args.find((a, i) => !a.startsWith("--") && !valueFlags.has(args[i - 1] ?? ""));
const mobileIdx = args.indexOf("--mobile");
const mobileVideo = mobileIdx >= 0 ? args[mobileIdx + 1] : undefined;
if (mobileVideo && !fs.existsSync(mobileVideo)) throw new Error(`No such file: ${mobileVideo}`);
const opt = (name: string, fallback: number) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? Number(args[i + 1]) : fallback;
};
if (!video || !fs.existsSync(video)) {
  console.error("Usage: tsx scripts/make-sequence.ts <video> [--frames 96] [--start 0] [--end <sec>]");
  process.exit(1);
}

const probeOf = (file: string) => {
  const p = JSON.parse(
    execFileSync("ffprobe", ["-v", "error", "-select_streams", "v:0", "-show_entries", "stream=width,height:format=duration", "-of", "json", file], { encoding: "utf8" }),
  ) as { streams: { width: number; height: number }[]; format: { duration: string } };
  return { ...p.streams[0]!, duration: Number(p.format.duration) };
};
const main = probeOf(video);
const { width, height } = main;
const start = opt("start", 0);
const end = Math.min(opt("end", main.duration), main.duration);
const span = end - start;
const frames = Math.max(24, Math.min(180, Math.round(opt("frames", 96))));
if (span <= 0) throw new Error(`Nothing to cut: start ${start}s, end ${end}s`);

const outRoot = path.join("public", "media", "transform");
fs.rmSync(outRoot, { recursive: true, force: true });

const phone = mobileVideo ? probeOf(mobileVideo) : null;
const variants = [
  { dir: "d", src: video, from: start, len: span, width: Math.min(1600, width), quality: 62 },
  // A vertical phone cut is sized by its own width (900px tall frames would be too small).
  phone
    ? { dir: "m", src: mobileVideo!, from: 0, len: phone.duration, width: Math.min(810, phone.width), quality: 58 }
    : { dir: "m", src: video, from: start, len: span, width: Math.min(900, width), quality: 58 },
];
const bytes: Record<string, number> = {};
for (const v of variants) {
  const dir = path.join(outRoot, v.dir);
  fs.mkdirSync(dir, { recursive: true });
  execFileSync(
    "ffmpeg",
    [
      "-v", "error", "-y",
      "-ss", String(v.from), "-t", String(v.len), "-i", v.src,
      // Evenly spaced frames across the clip, so scroll distance maps linearly to time.
      "-vf", `fps=${frames / v.len},scale=${v.width}:-2:flags=lanczos`,
      "-frames:v", String(frames),
      "-c:v", "libwebp", "-quality", String(v.quality), "-compression_level", "6", "-preset", "photo",
      path.join(dir, "%03d.webp"),
    ],
    { stdio: "inherit" },
  );
  const files = fs.readdirSync(dir).filter((f) => f.endsWith(".webp"));
  bytes[v.dir] = files.reduce((n, f) => n + fs.statSync(path.join(dir, f)).size, 0);
  if (files.length !== frames) console.warn(`${v.dir}: expected ${frames} frames, got ${files.length}`);
}
const count = fs.readdirSync(path.join(outRoot, "d")).filter((f) => f.endsWith(".webp")).length;
// The finished car: shown alone under reduced motion / data saver, and as the share-safe still.
fs.copyFileSync(path.join(outRoot, "d", `${String(count).padStart(3, "0")}.webp`), path.join(outRoot, "poster-end.webp"));
fs.copyFileSync(path.join(outRoot, "m", "001.webp"), path.join(outRoot, "poster-start.webp"));

const aspect = Number((width / height).toFixed(4));
fs.mkdirSync(path.join("lib", "media"), { recursive: true });
fs.writeFileSync(
  path.join("lib", "media", "sequences.ts"),
  `// Generated by scripts/make-sequence.ts from ${path.basename(video)} — do not edit by hand.
import type { FrameSequence } from "./sequence-types";

export const transformSequence: FrameSequence | null = {
  count: ${count},
  aspect: ${aspect},
  desktop: "/media/transform/d",
  mobile: "/media/transform/m",
  posterStart: "/media/transform/poster-start.webp",
  posterEnd: "/media/transform/poster-end.webp",
};
`,
);
const mb = (n: number) => `${(n / 1024 / 1024).toFixed(1)} MB`;
console.log(`${count} frames · aspect ${aspect} · desktop ${mb(bytes.d ?? 0)} · phone ${mb(bytes.m ?? 0)}`);
